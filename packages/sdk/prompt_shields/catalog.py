"""Model and provider catalog v1 (``catalog.json``).

The catalog ships with the SDK and is generated by ``scripts/build_catalog.py``
from ``schemas/catalog/source.v1.json``; do not edit ``catalog.json`` by hand.

Each model entry is keyed ``"<provider>/<model id>"`` and uses LiteLLM
``model_prices_and_context_window.json`` field names: per-token prices
(``input_cost_per_token``, ``cache_read_input_token_cost``,
``cache_creation_input_token_cost[_above_1hr]``,
``output_cost_per_reasoning_token``, ``*_above_200k_tokens``,
``*_batches``, ``*_flex``, audio), limits (``max_input_tokens``,
``max_output_tokens``) and capabilities (``supports_function_calling``,
``supports_response_schema``, ``supports_vision``, ``supports_reasoning``,
``supports_prompt_caching``). Prices are in the entry's ``currency``: USD,
or EUR for EU providers that list in euros. Only USD entries price events.

Every model also carries its provider's sovereignty fields:
``jurisdiction``, ``hosting_countries``, ``provider_hq_country``,
``us_cloud_act_exposure``, ``zdr``, ``trains_on_data`` and
``certifications``. ``None`` means unknown or not verified; a data policy
must treat it as non-compliant.

``prompt_shields.pricing`` builds its default rate tables from this catalog,
so ``estimate_cost`` keeps its signature and tuple-based ``pricing_table``.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Any

CATALOG_PATH = Path(__file__).with_name("catalog.json")

SOVEREIGNTY_FIELDS = (
    "jurisdiction",
    "hosting_countries",
    "provider_hq_country",
    "us_cloud_act_exposure",
    "zdr",
    "trains_on_data",
    "certifications",
)

# PRD names for the LiteLLM capability flags.
CAPABILITY_NAMES = {
    "tools": "supports_function_calling",
    "json_schema": "supports_response_schema",
    "vision": "supports_vision",
    "reasoning": "supports_reasoning",
    "prompt_caching": "supports_prompt_caching",
}

LONG_CONTEXT_THRESHOLD = 200_000

# Positional layouts of the SDK's rate tuples (see pricing.py).
_BASE_RATES = (
    "input_cost_per_token",
    "output_cost_per_token",
    "cache_read_input_token_cost",
    "cache_creation_input_token_cost",
    "cache_creation_input_token_cost_above_1hr",
)
_ABOVE_200K_RATES = (
    "input_cost_per_token_above_200k_tokens",
    "output_cost_per_token_above_200k_tokens",
    "cache_read_input_token_cost_above_200k_tokens",
    "cache_creation_input_token_cost_above_200k_tokens",
    "cache_creation_input_token_cost_above_1hr_above_200k_tokens",
)


def load_catalog(path: str | Path | None = None) -> dict[str, Any]:
    """The parsed catalog. The bundled one is cached; treat it as read-only."""
    if path is None:
        return _bundled()
    return json.loads(Path(path).read_text(encoding="utf-8"))


@lru_cache(maxsize=1)
def _bundled() -> dict[str, Any]:
    return json.loads(CATALOG_PATH.read_text(encoding="utf-8"))


def catalog_version(catalog: dict | None = None) -> str:
    return (catalog or load_catalog())["catalog_version"]


def get_model(provider: str, model: str, catalog: dict | None = None) -> dict | None:
    """The catalog entry for ``(provider, model)``, or None."""
    return (catalog or load_catalog())["models"].get(f"{provider}/{model}")


def get_provider(provider: str, catalog: dict | None = None) -> dict | None:
    return (catalog or load_catalog())["providers"].get(provider)


def iter_models(catalog: dict | None = None, **filters: Any):
    """Yield model entries whose fields equal every ``filters`` value.

    ``iter_models(jurisdiction="EEA", us_cloud_act_exposure=False)``
    """
    for entry in (catalog or load_catalog())["models"].values():
        if all(entry.get(k) == v for k, v in filters.items()):
            yield entry


def sovereignty(entry: dict) -> dict[str, Any]:
    """The sovereignty fields of a model entry."""
    return {field: entry.get(field) for field in SOVEREIGNTY_FIELDS}


def capabilities(entry: dict) -> dict[str, Any]:
    """Capabilities under PRD names (``tools``, ``json_schema``, ``vision``,
    ``reasoning``, ``prompt_caching``) plus ``max_input_tokens``. A flag the
    catalog does not set is False; an unknown limit is None."""
    caps: dict[str, Any] = {
        name: bool(entry.get(field)) for name, field in CAPABILITY_NAMES.items()
    }
    caps["max_input_tokens"] = entry.get("max_input_tokens")
    return caps


def _per_1k(per_token: float) -> float:
    return round(per_token * 1000, 12)


def _rate_tuple(entry: dict, fields: tuple[str, ...]) -> tuple[float, ...] | None:
    rates = []
    for field in fields:
        if field not in entry:
            break
        rates.append(_per_1k(entry[field]))
    return tuple(rates) if len(rates) >= 2 else None


def _usd_entries(catalog: dict | None):
    for entry in (catalog or load_catalog())["models"].values():
        if entry.get("currency", "USD") == "USD" and "input_cost_per_token" in entry:
            yield entry


def pricing_table(catalog: dict | None = None) -> dict[tuple[str, str], tuple[float, ...]]:
    """USD token rates as ``pricing.DEFAULT_PRICING`` tuples, per 1k tokens:
    ``(input, output[, cache_read[, cache_write[, cache_write_1h]]])``.

    Cache rates the catalog leaves out fall back to the vendor multipliers in
    ``pricing.py``. Non-USD entries are left out (their calls stay unpriced).
    """
    table = {}
    for entry in _usd_entries(catalog):
        rates = _rate_tuple(entry, _BASE_RATES)
        if rates is not None:
            table[(entry["provider"], entry["model"])] = rates
    return table


def long_context_pricing(
    catalog: dict | None = None,
) -> dict[tuple[str, str], tuple[int, tuple[float, ...]]]:
    """``(200_000, rates)`` for USD models with ``*_above_200k_tokens`` prices."""
    bands = {}
    for entry in _usd_entries(catalog):
        rates = _rate_tuple(entry, _ABOVE_200K_RATES)
        if rates is not None:
            bands[(entry["provider"], entry["model"])] = (LONG_CONTEXT_THRESHOLD, rates)
    return bands


def audio_pricing(catalog: dict | None = None) -> dict[tuple[str, str], tuple[float, float]]:
    """``(audio_input, audio_output)`` per 1k tokens for USD models that bill
    audio tokens apart from text."""
    rates = {}
    for entry in _usd_entries(catalog):
        if "input_cost_per_audio_token" in entry and "output_cost_per_audio_token" in entry:
            rates[(entry["provider"], entry["model"])] = (
                _per_1k(entry["input_cost_per_audio_token"]),
                _per_1k(entry["output_cost_per_audio_token"]),
            )
    return rates
