#!/usr/bin/env python3
"""Build the model catalog and the gateway's default route policy.

Reads the hand-maintained source, ``schemas/catalog/source.v1.json``, and
writes three generated files:

- ``packages/sdk/prompt_shields/catalog.json``: the SDK catalog (catalog v1).
  Model entries use LiteLLM ``model_prices_and_context_window.json`` field
  names, plus the provider's sovereignty fields copied onto every model.
- ``gateway/src/middlewares/router/defaultPolicy.json``: the gateway router's
  default ``RoutePolicy``, with per-1k prices taken from the catalog.
- ``gateway/src/middlewares/psPricingTables.json``: the token rate tables
  the gateway prices telemetry events with (psPricing.ts), built exactly as
  the SDK's ``catalog.py`` builds ``pricing.DEFAULT_PRICING``,
  ``LONG_CONTEXT_PRICING`` and ``AUDIO_PRICING``.

Usage::

    python scripts/build_catalog.py            # regenerate the files
    python scripts/build_catalog.py --check    # exit 1 if any file drifted
    python scripts/build_catalog.py --litellm PATH/model_prices_and_context_window.json
        # also report entries whose prices differ from LiteLLM (informational)

Standard library only; no network.
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "schemas" / "catalog" / "source.v1.json"
SDK_CATALOG = ROOT / "packages" / "sdk" / "prompt_shields" / "catalog.json"
GATEWAY_POLICY = ROOT / "gateway" / "src" / "middlewares" / "router" / "defaultPolicy.json"
GATEWAY_PRICING = ROOT / "gateway" / "src" / "middlewares" / "psPricingTables.json"

SCHEMA_VERSION = 1
CURRENCIES = ("USD", "EUR")
SOVEREIGNTY_FIELDS = (
    "jurisdiction",
    "hosting_countries",
    "provider_hq_country",
    "us_cloud_act_exposure",
    "zdr",
    "trains_on_data",
    "certifications",
)
PROVIDER_FIELDS = (
    "name",
    "kind",
    "api_base",
    "openai_compatible",
    *SOVEREIGNTY_FIELDS,
    "notes",
)
PROVIDER_KINDS = ("direct", "cloud", "sovereign", "aggregator")

# LiteLLM price fields the catalog carries, per token in the entry's currency.
PRICE_FIELDS = (
    "input_cost_per_token",
    "output_cost_per_token",
    "cache_read_input_token_cost",
    "cache_creation_input_token_cost",
    "cache_creation_input_token_cost_above_1hr",
    "output_cost_per_reasoning_token",
    "input_cost_per_token_above_200k_tokens",
    "output_cost_per_token_above_200k_tokens",
    "cache_read_input_token_cost_above_200k_tokens",
    "cache_creation_input_token_cost_above_200k_tokens",
    "cache_creation_input_token_cost_above_1hr_above_200k_tokens",
    "input_cost_per_token_batches",
    "output_cost_per_token_batches",
    "input_cost_per_token_flex",
    "output_cost_per_token_flex",
    "input_cost_per_audio_token",
    "output_cost_per_audio_token",
)
# Capabilities and limits, LiteLLM names.
CAPABILITY_FIELDS = (
    "supports_function_calling",
    "supports_response_schema",
    "supports_vision",
    "supports_reasoning",
    "supports_prompt_caching",
)
LIMIT_FIELDS = ("max_input_tokens", "max_output_tokens")
OTHER_FIELDS = ("mode", "deprecation_date", "litellm_key", "currency", "source", "comment")
MODEL_FIELDS = (*OTHER_FIELDS, *LIMIT_FIELDS, *CAPABILITY_FIELDS, *PRICE_FIELDS, *SOVEREIGNTY_FIELDS)

# A later field of each chain needs the earlier ones (the SDK's rate tuple is
# positional: input, output, cache read, cache write, 1h cache write).
PRICE_CHAINS = (
    (
        "input_cost_per_token",
        "output_cost_per_token",
        "cache_read_input_token_cost",
        "cache_creation_input_token_cost",
        "cache_creation_input_token_cost_above_1hr",
    ),
    (
        "input_cost_per_token_above_200k_tokens",
        "output_cost_per_token_above_200k_tokens",
        "cache_read_input_token_cost_above_200k_tokens",
        "cache_creation_input_token_cost_above_200k_tokens",
        "cache_creation_input_token_cost_above_1hr_above_200k_tokens",
    ),
    ("input_cost_per_token_batches", "output_cost_per_token_batches"),
    ("input_cost_per_token_flex", "output_cost_per_token_flex"),
)
COUNTRY = re.compile(r"^[A-Z]{2}$")
JURISDICTIONS = ("EEA", "US", "NO", "CH", "UK", "CA")
VERSION = re.compile(r"^\d{4}-\d{2}-\d{2}(\.\d+)?$")

SDK_HEADER = (
    "Generated by scripts/build_catalog.py from schemas/catalog/source.v1.json. "
    "Do not edit; edit the source and regenerate."
)


class CatalogError(ValueError):
    pass


def _is_number(value) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _check_sovereignty(where: str, record: dict, *, partial: bool) -> list[str]:
    errors = []
    for field in SOVEREIGNTY_FIELDS:
        if field not in record:
            if not partial:
                errors.append(f"{where}: missing {field}")
            continue
        value = record[field]
        if field == "jurisdiction":
            if value is not None and value not in JURISDICTIONS:
                errors.append(f"{where}: jurisdiction {value!r} not in {JURISDICTIONS}")
        elif field == "provider_hq_country":
            if value is not None and not (isinstance(value, str) and COUNTRY.match(value)):
                errors.append(f"{where}: provider_hq_country must be ISO 3166 alpha-2 or null")
        elif field == "hosting_countries":
            if value is not None and not (
                isinstance(value, list)
                and value
                and all(isinstance(c, str) and COUNTRY.match(c) for c in value)
            ):
                errors.append(f"{where}: hosting_countries must be a non-empty list of alpha-2 codes or null")
        elif field == "certifications":
            if not (isinstance(value, list) and all(isinstance(c, str) and c for c in value)):
                errors.append(f"{where}: certifications must be a list of strings")
        elif value is not None and not isinstance(value, bool):
            errors.append(f"{where}: {field} must be true, false or null")
    return errors


def validate(source: dict) -> None:
    """Raise CatalogError listing every problem in the source."""
    errors: list[str] = []
    version = source.get("catalog_version")
    if not (isinstance(version, str) and VERSION.match(version)):
        errors.append("catalog_version must look like YYYY-MM-DD or YYYY-MM-DD.N")

    providers = source.get("providers")
    if not isinstance(providers, dict) or not providers:
        raise CatalogError("providers must be a non-empty object")
    for pid, provider in providers.items():
        where = f"provider {pid}"
        unknown = set(provider) - set(PROVIDER_FIELDS)
        if unknown:
            errors.append(f"{where}: unknown fields {sorted(unknown)}")
        if provider.get("kind") not in PROVIDER_KINDS:
            errors.append(f"{where}: kind must be one of {PROVIDER_KINDS}")
        errors += _check_sovereignty(where, provider, partial=False)

    models = source.get("models")
    if not isinstance(models, dict) or not models:
        raise CatalogError("models must be a non-empty object")
    for key, entry in models.items():
        where = f"model {key}"
        pid, sep, model = key.partition("/")
        if not sep or not model:
            errors.append(f"{where}: key must be '<provider>/<model id>'")
            continue
        if pid not in providers:
            errors.append(f"{where}: unknown provider {pid!r}")
        unknown = set(entry) - set(MODEL_FIELDS)
        if unknown:
            errors.append(f"{where}: unknown fields {sorted(unknown)}")
        if not isinstance(entry.get("mode"), str):
            errors.append(f"{where}: mode is required")
        if not isinstance(entry.get("source"), str):
            errors.append(f"{where}: source is required")
        if entry.get("currency", "USD") not in CURRENCIES:
            errors.append(f"{where}: currency must be one of {CURRENCIES}")
        for field in PRICE_FIELDS:
            if field in entry and not (_is_number(entry[field]) and entry[field] >= 0):
                errors.append(f"{where}: {field} must be a number >= 0")
        for field in LIMIT_FIELDS:
            if field in entry and not (isinstance(entry[field], int) and entry[field] > 0):
                errors.append(f"{where}: {field} must be a positive integer")
        for field in CAPABILITY_FIELDS:
            if field in entry and not isinstance(entry[field], bool):
                errors.append(f"{where}: {field} must be a boolean")
        for chain in PRICE_CHAINS:
            present = [field in entry for field in chain]
            # Input and output come as a pair; later fields need earlier ones.
            if present[0] != present[1]:
                errors.append(f"{where}: {chain[0]} and {chain[1]} go together")
            for i in range(2, len(chain)):
                if present[i] and not present[i - 1]:
                    errors.append(f"{where}: {chain[i]} needs {chain[i - 1]}")
        if any(f in entry for f in PRICE_FIELDS) and "input_cost_per_token" not in entry:
            errors.append(f"{where}: priced fields need input_cost_per_token")
        errors += _check_sovereignty(where, entry, partial=True)

    router = source.get("router") or {}
    groups = router.get("groups") or {}
    if router.get("defaultGroup") not in groups:
        errors.append("router: defaultGroup must name a group")
    for quality in ("draft", "balanced", "critical"):
        if (router.get("qualityToGroup") or {}).get(quality) not in groups:
            errors.append(f"router: qualityToGroup.{quality} must name a group")
    for group, keys in groups.items():
        if not keys:
            errors.append(f"router: group {group} is empty")
        for key in keys:
            entry = models.get(key)
            if entry is None:
                errors.append(f"router: group {group} names unknown model {key}")
            elif entry.get("currency", "USD") != "USD" or "input_cost_per_token" not in entry:
                errors.append(f"router: group {group} model {key} needs USD prices")

    if errors:
        raise CatalogError("\n".join(errors))


def build_sdk_catalog(source: dict) -> dict:
    providers = {
        pid: {field: provider[field] for field in PROVIDER_FIELDS if field in provider}
        for pid, provider in source["providers"].items()
    }
    models = {}
    for key, entry in source["models"].items():
        pid, _, model = key.partition("/")
        out = {"provider": pid, "model": model}
        out["currency"] = entry.get("currency", "USD")
        for field in MODEL_FIELDS:
            if field in entry and field not in SOVEREIGNTY_FIELDS and field != "currency":
                out[field] = entry[field]
        for field in SOVEREIGNTY_FIELDS:
            out[field] = entry.get(field, providers[pid][field])
        models[key] = out
    return {
        "_generated": SDK_HEADER,
        "schema_version": SCHEMA_VERSION,
        "catalog_version": source["catalog_version"],
        "sovereignty_checked": source.get("sovereignty_checked"),
        "notes": source.get("notes", []),
        "providers": providers,
        "models": models,
    }


def per_1k(per_token: float) -> float:
    # Round off float noise from the unit change (2.5e-06 * 1000).
    return round(per_token * 1000, 12)


def build_gateway_policy(source: dict) -> dict:
    router = source["router"]
    groups = {}
    for group, keys in router["groups"].items():
        tiers = []
        for key in keys:
            entry = source["models"][key]
            tiers.append(
                {
                    "model": key.partition("/")[2],
                    "group": group,
                    "inputCostPer1k": per_1k(entry["input_cost_per_token"]),
                    "outputCostPer1k": per_1k(entry["output_cost_per_token"]),
                }
            )
        groups[group] = tiers
    return {
        "_generated": SDK_HEADER,
        "catalogVersion": source["catalog_version"],
        "defaultGroup": router["defaultGroup"],
        "qualityToGroup": router["qualityToGroup"],
        "groups": groups,
    }


LONG_CONTEXT_THRESHOLD = 200_000


def _rate_list(entry: dict, fields: tuple[str, ...]) -> list[float] | None:
    # As catalog._rate_tuple: the leading run of present fields, at least 2.
    rates = []
    for field in fields:
        if field not in entry:
            break
        rates.append(per_1k(entry[field]))
    return rates if len(rates) >= 2 else None


def build_gateway_pricing(source: dict) -> dict:
    """USD token rates per 1k tokens, keyed "<provider>/<model id>", as the
    SDK's catalog.py builds them (pricing_table, long_context_pricing,
    audio_pricing). Non-USD and unpriced entries are left out."""
    tokens, long_context, audio = {}, {}, {}
    for key, entry in source["models"].items():
        if entry.get("currency", "USD") != "USD" or "input_cost_per_token" not in entry:
            continue
        rates = _rate_list(entry, PRICE_CHAINS[0])
        if rates is not None:
            tokens[key] = rates
        band = _rate_list(entry, PRICE_CHAINS[1])
        if band is not None:
            long_context[key] = {"threshold": LONG_CONTEXT_THRESHOLD, "rates": band}
        if "input_cost_per_audio_token" in entry and "output_cost_per_audio_token" in entry:
            audio[key] = [
                per_1k(entry["input_cost_per_audio_token"]),
                per_1k(entry["output_cost_per_audio_token"]),
            ]
    return {
        "_generated": SDK_HEADER,
        "catalogVersion": source["catalog_version"],
        "tokenPricing": tokens,
        "longContextPricing": long_context,
        "audioPricing": audio,
    }


def render(data: dict) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def outputs(source: dict) -> dict[Path, str]:
    validate(source)
    return {
        SDK_CATALOG: render(build_sdk_catalog(source)),
        GATEWAY_POLICY: render(build_gateway_policy(source)),
        GATEWAY_PRICING: render(build_gateway_pricing(source)),
    }


def litellm_report(source: dict, litellm_path: Path) -> list[str]:
    """Price fields that differ from the LiteLLM entry named by `litellm_key`."""
    litellm = json.loads(litellm_path.read_text())
    lines = []
    for key, entry in source["models"].items():
        lkey = entry.get("litellm_key")
        if not lkey:
            continue
        ref = litellm.get(lkey)
        if ref is None:
            lines.append(f"{key}: LiteLLM has no {lkey!r}")
            continue
        for field in PRICE_FIELDS:
            ours, theirs = entry.get(field), ref.get(field)
            if ours is None and theirs is None:
                continue
            if ours is None or theirs is None or abs(ours - theirs) > 1e-15:
                lines.append(f"{key}: {field} catalog={ours} litellm={theirs}")
    return lines


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    parser.add_argument("--litellm", type=Path, help="LiteLLM price map to compare prices against")
    args = parser.parse_args(argv)

    source = json.loads(SOURCE.read_text())
    try:
        files = outputs(source)
    except CatalogError as exc:
        print(f"catalog source is invalid:\n{exc}", file=sys.stderr)
        return 1

    status = 0
    for path, text in files.items():
        rel = path.relative_to(ROOT)
        current = path.read_text() if path.exists() else ""
        if current == text:
            continue
        if args.check:
            status = 1
            print(f"{rel} is out of date. Run: python scripts/build_catalog.py", file=sys.stderr)
            diff = difflib.unified_diff(
                current.splitlines(), text.splitlines(), f"{rel} (committed)", f"{rel} (generated)", lineterm=""
            )
            for line in list(diff)[:60]:
                print(line, file=sys.stderr)
        else:
            path.write_text(text)
            print(f"wrote {rel}")

    if args.litellm:
        for line in litellm_report(source, args.litellm):
            print(f"litellm drift: {line}")
    return status


if __name__ == "__main__":
    sys.exit(main())
